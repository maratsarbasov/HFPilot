"""The call lifecycle depends on this contract, never on D-Bus or Skywalk."""
from typing import Protocol


class Phone(Protocol):
    name: str

    def validate(self): ...
    async def start(self): ...
    def read(self) -> tuple[str, dict[str, str]]: ...
    def caller(self, call: str) -> dict | None: ...
    async def prepare_caller(self, call: str) -> dict: ...
    async def answer(self, call: str): ...
    async def hangup(self, call: str): ...
    def audio(self, journal, input_gain, output_gain, record): ...
    async def close(self): ...


def create_phone(args, *, continuous=False):
    if args.backend == 'skywalk':
        from .skywalk import SkywalkPhone
        return SkywalkPhone(args.address, args.skywalk_binary, args.bond_file,
                            0 if continuous else
                            (args.dial_timeout if args.command == 'dial' else args.wait) + args.max_call + 120,
                            buffer_ms=args.skywalk_buffer_ms, codec=args.skywalk_codec)
    from .pipewire import PipeWirePhone
    return PipeWirePhone(args.address)
